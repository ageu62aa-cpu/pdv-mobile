CREATE TABLE IF NOT EXISTS public.maquininhas_taxas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
    nome_maquina text NOT NULL CHECK (length(trim(nome_maquina)) > 0),
    taxa_debito numeric(7, 4) NOT NULL DEFAULT 0 CHECK (taxa_debito BETWEEN 0 AND 100),
    taxa_credito_avista numeric(7, 4) NOT NULL DEFAULT 0 CHECK (taxa_credito_avista BETWEEN 0 AND 100),
    taxas_parcelamento jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.maquininhas_taxas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS maquininhas_taxas_select_empresa ON public.maquininhas_taxas;
CREATE POLICY maquininhas_taxas_select_empresa
    ON public.maquininhas_taxas
    FOR SELECT
    TO authenticated
    USING (
        EXISTS (
            SELECT 1
            FROM public.usuarios_empresas ue
            WHERE ue.user_id::text = auth.uid()::text
              AND ue.empresa_id::text = maquininhas_taxas.empresa_id::text
        )
        OR EXISTS (
            SELECT 1
            FROM public.empresas e
            WHERE e.id::text = maquininhas_taxas.empresa_id::text
              AND (e.id::text = auth.uid()::text OR e.email_admin::text = auth.jwt() ->> 'email')
        )
    );

