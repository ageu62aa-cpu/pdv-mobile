CREATE TABLE IF NOT EXISTS public.cancelamentos_caixa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
    caixa_id uuid NOT NULL REFERENCES public.caixas(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES auth.users(id),
    quantidade numeric(12, 3) NOT NULL CHECK (quantidade > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cancelamentos_caixa_empresa_data_idx
    ON public.cancelamentos_caixa (empresa_id, created_at);

ALTER TABLE public.cancelamentos_caixa ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS cancelamentos_caixa_select_empresa ON public.cancelamentos_caixa;
CREATE POLICY cancelamentos_caixa_select_empresa
    ON public.cancelamentos_caixa
    FOR SELECT
    TO authenticated
    USING (
        user_id = auth.uid()
        OR EXISTS (
            SELECT 1
            FROM public.usuarios_empresas ue
            WHERE ue.user_id = auth.uid()
              AND ue.empresa_id = cancelamentos_caixa.empresa_id
              AND ue.cargo = 'admin_mercado'
        )
        OR EXISTS (
            SELECT 1
            FROM public.empresas e
            WHERE e.id = cancelamentos_caixa.empresa_id
              AND (e.id = auth.uid() OR e.email_admin = auth.jwt() ->> 'email')
        )
    );

DROP POLICY IF EXISTS cancelamentos_caixa_insert_open_cash ON public.cancelamentos_caixa;
CREATE POLICY cancelamentos_caixa_insert_open_cash
    ON public.cancelamentos_caixa
    FOR INSERT
    TO authenticated
    WITH CHECK (
        user_id = auth.uid()
        AND EXISTS (
            SELECT 1
            FROM public.caixas c
            WHERE c.id = cancelamentos_caixa.caixa_id
              AND c.empresa_id = cancelamentos_caixa.empresa_id
              AND c.user_id = auth.uid()
              AND c.status = 'ABERTO'
        )
    );

GRANT SELECT, INSERT ON public.cancelamentos_caixa TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.cancelamentos_caixa_id_seq TO authenticated;

DO $$
DECLARE
    tabela text;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
        FOREACH tabela IN ARRAY ARRAY['cancelamentos_caixa', 'operadores', 'usuarios_empresas']
        LOOP
            IF NOT EXISTS (
                SELECT 1
                FROM pg_publication_tables
                WHERE pubname = 'supabase_realtime'
                  AND schemaname = 'public'
                  AND tablename = tabela
            ) THEN
                EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', tabela);
            END IF;
        END LOOP;
    END IF;
END
$$;
