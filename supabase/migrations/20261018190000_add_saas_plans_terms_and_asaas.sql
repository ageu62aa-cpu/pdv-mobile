CREATE TABLE IF NOT EXISTS public.planos (
    id text PRIMARY KEY,
    nome text NOT NULL UNIQUE,
    preco_mensal numeric(10, 2) NOT NULL CHECK (preco_mensal >= 0),
    limite_operadores integer NOT NULL CHECK (limite_operadores >= 0),
    limite_dispositivos integer NOT NULL CHECK (limite_dispositivos >= 1),
    limite_produtos integer NOT NULL CHECK (limite_produtos >= 1),
    dias_historico integer,
    limite_notas_mensais integer,
    CHECK (dias_historico IS NULL OR dias_historico > 0),
    CHECK (limite_notas_mensais IS NULL OR limite_notas_mensais >= 0)
);

