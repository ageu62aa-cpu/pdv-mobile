CREATE OR REPLACE FUNCTION public.vancely_get_tenant_entitlements(p_empresa_id uuid)
RETURNS TABLE (
    plano_id text,
    nome text,
    preco_mensal numeric,
    limite_operadores integer,
    limite_dispositivos integer,
    limite_produtos integer,
    dias_historico integer,
    limite_notas_mensais integer,
    status_assinatura text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
    SELECT p.id, p.nome, p.preco_mensal,
           p.limite_operadores, p.limite_dispositivos, p.limite_produtos,
           p.dias_historico, p.limite_notas_mensais,
           e.status_assinatura
    FROM public.empresas e
    JOIN public.planos p ON p.id = coalesce((
        SELECT a.plano_id
        FROM public.assinaturas a
        WHERE a.empresa_id = e.id
          AND a.status IN ('ACTIVE', 'TRIALING')
        ORDER BY a.updated_at DESC
        LIMIT 1
    ), e.plano_id)
    WHERE e.id = p_empresa_id
      AND (
          public.vancely_is_company_admin(e.id)
          OR EXISTS (
              SELECT 1 FROM public.usuarios_empresas ue
              WHERE ue.empresa_id = e.id AND ue.user_id = auth.uid()
          )
      );
$$;

REVOKE ALL ON FUNCTION public.vancely_get_tenant_entitlements(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.vancely_get_tenant_entitlements(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.pdv_register_active_session(p_device_id text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_empresa_id uuid;
    v_limite integer;
    v_token text := 'sessao_' || gen_random_uuid()::text;
    v_email text := auth.jwt() ->> 'email';
BEGIN
    IF v_user_id IS NULL OR p_device_id IS NULL OR length(p_device_id) < 8 OR length(p_device_id) > 128 THEN
        RAISE EXCEPTION 'Sessão ou identificador do dispositivo inválido.';
    END IF;

    SELECT ue.empresa_id INTO v_empresa_id
    FROM public.usuarios_empresas ue
    WHERE ue.user_id = v_user_id
    LIMIT 1;

    IF v_empresa_id IS NULL THEN
        SELECT e.id INTO v_empresa_id
        FROM public.empresas e
        WHERE e.id = v_user_id
           OR lower(coalesce(e.email_admin, e.email, '')) = lower(coalesce(v_email, ''))
        LIMIT 1;
    END IF;

    IF v_empresa_id IS NULL THEN
        RAISE EXCEPTION 'Não foi possível localizar a empresa vinculada à conta.';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(v_empresa_id::text, 0));

    SELECT p.limite_dispositivos INTO v_limite
    FROM public.planos p
    JOIN public.empresas e ON e.plano_id = p.id
    WHERE e.id = v_empresa_id;

    SELECT p.limite_dispositivos INTO v_limite
    FROM public.assinaturas a
    JOIN public.planos p ON p.id = a.plano_id
    WHERE a.empresa_id = v_empresa_id
      AND a.status IN ('ACTIVE', 'TRIALING')
    ORDER BY a.updated_at DESC
    LIMIT 1;

    IF v_limite IS NULL THEN
        SELECT p.limite_dispositivos INTO v_limite
        FROM public.empresas e
        JOIN public.planos p ON p.id = e.plano_id
        WHERE e.id = v_empresa_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.sessoes_ativas s
        WHERE s.empresa_id = v_empresa_id
          AND s.updated_at > now() - interval '5 minutes'
          AND s.device_id = p_device_id
          AND s.user_id <> v_user_id
    ) AND (
        SELECT count(DISTINCT s.device_id)
        FROM public.sessoes_ativas s
        WHERE s.empresa_id = v_empresa_id
          AND s.updated_at > now() - interval '5 minutes'
          AND s.user_id <> v_user_id
    ) >= v_limite THEN
        RAISE EXCEPTION 'O plano % permite até % dispositivo(s) conectado(s). Desconecte outro dispositivo ou faça upgrade.',
            (SELECT p.nome FROM public.planos p JOIN public.empresas e ON e.plano_id = p.id WHERE e.id = v_empresa_id),
            v_limite;
    END IF;

    DELETE FROM public.sessoes_ativas WHERE user_id = v_user_id;

    INSERT INTO public.sessoes_ativas (user_id, empresa_id, device_id, token_sessao, updated_at)
    VALUES (v_user_id, v_empresa_id, p_device_id, v_token, now());

    RETURN v_token;
END;
$$;

REVOKE ALL ON FUNCTION public.pdv_register_active_session(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pdv_register_active_session(text) TO authenticated;

