CREATE OR REPLACE FUNCTION public.pdv_enforce_product_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
    v_limite integer;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended(NEW.empresa_id::text, 1));

    SELECT p.limite_produtos INTO v_limite
    FROM public.empresas e
    JOIN public.planos p ON p.id = e.plano_id
    WHERE e.id = NEW.empresa_id;

    SELECT p.limite_produtos INTO v_limite
    FROM public.assinaturas a
    JOIN public.planos p ON p.id = a.plano_id
    WHERE a.empresa_id = NEW.empresa_id
      AND a.status IN ('ACTIVE', 'TRIALING')
    ORDER BY a.updated_at DESC
    LIMIT 1;

    IF v_limite IS NULL THEN
        SELECT p.limite_produtos INTO v_limite
        FROM public.empresas e JOIN public.planos p ON p.id = e.plano_id
        WHERE e.id = NEW.empresa_id;
    END IF;

    IF (SELECT count(*) FROM public.produtos WHERE empresa_id = NEW.empresa_id) >= v_limite THEN
        RAISE EXCEPTION 'Limite de % produtos do plano atingido. Faça upgrade para cadastrar mais.', v_limite;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS produtos_enforce_plan_limit ON public.produtos;
CREATE TRIGGER produtos_enforce_plan_limit
    BEFORE INSERT ON public.produtos
    FOR EACH ROW EXECUTE FUNCTION public.pdv_enforce_product_limit();

CREATE OR REPLACE FUNCTION public.pdv_enforce_operator_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
    v_limite integer;
BEGIN
    IF NEW.cargo <> 'operador' THEN RETURN NEW; END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(NEW.empresa_id::text, 2));

    SELECT p.limite_operadores INTO v_limite
    FROM public.empresas e JOIN public.planos p ON p.id = e.plano_id
    WHERE e.id = NEW.empresa_id;
    SELECT p.limite_operadores INTO v_limite
    FROM public.assinaturas a JOIN public.planos p ON p.id = a.plano_id
    WHERE a.empresa_id = NEW.empresa_id AND a.status IN ('ACTIVE', 'TRIALING')
    ORDER BY a.updated_at DESC LIMIT 1;
    IF v_limite IS NULL THEN
        SELECT p.limite_operadores INTO v_limite
        FROM public.empresas e JOIN public.planos p ON p.id = e.plano_id
        WHERE e.id = NEW.empresa_id;
    END IF;

    IF (SELECT count(*) FROM public.usuarios_empresas
        WHERE empresa_id = NEW.empresa_id AND cargo = 'operador') >= v_limite THEN
        RAISE EXCEPTION 'Limite de % operador(es) do plano atingido. Faça upgrade para cadastrar mais.', v_limite;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS usuarios_empresas_enforce_operator_limit ON public.usuarios_empresas;
CREATE TRIGGER usuarios_empresas_enforce_operator_limit
    BEFORE INSERT ON public.usuarios_empresas
    FOR EACH ROW EXECUTE FUNCTION public.pdv_enforce_operator_limit();

CREATE OR REPLACE FUNCTION public.pdv_activate_subscription_from_asaas(
    p_asaas_subscription_id text,
    p_payment_id text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_assinatura public.assinaturas%ROWTYPE;
BEGIN
    SELECT * INTO v_assinatura
    FROM public.assinaturas
    WHERE asaas_subscription_id = p_asaas_subscription_id
    FOR UPDATE;
    IF NOT FOUND THEN RETURN false; END IF;

    UPDATE public.assinaturas
    SET status = 'ACTIVE',
        ultimo_pagamento_id = p_payment_id,
        periodo_inicio = now(),
        updated_at = now()
    WHERE id = v_assinatura.id;

    UPDATE public.empresas
    SET plano_id = v_assinatura.plano_id,
        plano = v_assinatura.plano_id,
        status_assinatura = 'ATIVO'
    WHERE id = v_assinatura.empresa_id;
    RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.pdv_activate_subscription_from_asaas(text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.pdv_activate_subscription_from_asaas(text, text) TO service_role;

